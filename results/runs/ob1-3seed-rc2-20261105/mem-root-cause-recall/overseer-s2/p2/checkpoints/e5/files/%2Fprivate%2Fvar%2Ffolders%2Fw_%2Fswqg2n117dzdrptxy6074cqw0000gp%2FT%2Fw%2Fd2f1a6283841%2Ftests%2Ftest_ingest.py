import os
import shutil
import tempfile
import unittest
from decimal import Decimal

from meridian import report, text
from meridian.ingest import apac, eu

FEEDS = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "feeds")


class FeedCase(unittest.TestCase):
    def feed(self, name, content):
        """Write a feed file into a temp dir and return its path."""
        d = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, d)
        path = os.path.join(d, name)
        with open(path, "w", encoding="utf-8") as f:
            f.write(content)
        return path


class TestCleanNumber(unittest.TestCase):
    def test_v1_uses_dot_grouping_and_decimal_comma(self):
        self.assertEqual(text.clean_number("1.234,56"), "1234.56")
        self.assertEqual(text.clean_number("99,99"), "99.99")

    def test_v2_uses_comma_grouping_and_decimal_dot(self):
        self.assertEqual(text.clean_number("1234.56", "v2"), "1234.56")
        self.assertEqual(text.clean_number("1,234.56", "v2"), "1234.56")
        self.assertEqual(text.clean_number("99.99", "v2"), "99.99")

    def test_unknown_format_is_rejected(self):
        with self.assertRaises(ValueError):
            text.clean_number("1234.56", "v9")


class TestFeedFormat(FeedCase):
    def test_declared_format_is_read(self):
        path = self.feed("eu.csv", "# region: eu\n# format: v2\n")
        with open(path, encoding="utf-8") as f:
            self.assertEqual(text.feed_format(f.read().splitlines()), "v2")

    def test_missing_header_defaults_to_v1(self):
        self.assertEqual(text.feed_format(["# region: eu"]), "v1")


class TestEuReader(FeedCase):
    def test_v2_amounts_are_not_scaled(self):
        path = self.feed(
            "eu.csv",
            "# region: eu\n# format: v2\n# generated by the eu ledger export\n"
            "date;account;amount\n2026-10-03;AC-3413;1425.01\n2026-10-08;AC-1205;856.98\n",
        )
        self.assertEqual(
            [r["amount"] for r in eu.read_feed(path)],
            [Decimal("1425.01"), Decimal("856.98")],
        )

    def test_v1_amounts_are_unchanged(self):
        path = self.feed(
            "eu.csv",
            "# region: eu\n# format: v1\ndate;account;amount\n2026-09-27;AC-3239;4.014,05\n",
        )
        self.assertEqual([r["amount"] for r in eu.read_feed(path)], [Decimal("4014.05")])

    def test_unknown_format_is_rejected(self):
        path = self.feed(
            "eu.csv",
            "# region: eu\n# format: v9\ndate;account;amount\n2026-10-03;AC-3413;1425.01\n",
        )
        with self.assertRaises(ValueError):
            eu.read_feed(path)


class TestApacReader(FeedCase):
    def test_v2_amounts_are_not_scaled(self):
        path = self.feed(
            "apac.csv",
            "# region: apac\n# format: v2\ndate|account|amount\n"
            "2026-10-11|AC-1381|2641.49\n2026-10-21|AC-2684|4995.20\n",
        )
        self.assertEqual(
            [r["amount"] for r in apac.load(path)],
            [Decimal("2641.49"), Decimal("4995.20")],
        )

    def test_v1_space_grouping_is_unchanged(self):
        path = self.feed(
            "apac.csv",
            "# region: apac\n# format: v1\ndate|account|amount\n"
            "2026-09-02|AC-9426|1 114,82\n",
        )
        self.assertEqual([r["amount"] for r in apac.load(path)], [Decimal("1114.82")])


class TestMonthlyTotals(FeedCase):
    """Regression: October 2026 ships feeds in format v2, amounts are already
    dot-decimals, so the totals must not be inflated a hundredfold."""

    def test_eu_october_matches_finance(self):
        self.assertEqual(report.total("eu", "2026-10", FEEDS), Decimal("1774765.57"))

    def test_eu_september_is_unchanged(self):
        self.assertEqual(report.total("eu", "2026-09", FEEDS), Decimal("1734482.25"))

    def test_apac_october_matches_finance(self):
        self.assertEqual(report.total("apac", "2026-10", FEEDS), Decimal("1787313.21"))
