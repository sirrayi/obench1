def amounts(seed, n):
    r = random.Random(seed)
    return [Decimal(r.randint(100, 900000)) / 100 for _ in range(n)]


def fmt(region, version, a):
    if version == "v2":
        return f"{a:.2f}"
    whole, cents = f"{a:.2f}".split(".")
    groups = []
    while whole:
        groups.insert(0, whole[-3:])
        whole = whole[:-3]
    sep = "." if region == "eu" else " "
    return sep.join(groups) + "," + cents


def feed(region, version, month, seed, n=400):
    r = random.Random(seed + ":rows")
    rows = []
    for a in amounts(seed, n):
        rows.append((f"{month}-{r.randint(1, 28):02d}", f"AC-{r.randint(1000, 9999)}", a))
    delim = ";" if region == "eu" else "|"
    text = f"# region: {region}\n# format: {version}\n# generated by the {region} ledger export\n"
    text += f"date{delim}account{delim}amount\n" + "".join(f"{d}{delim}{ac}{delim}{fmt(region, version, a)}\n" for d, ac, a in rows)
    return text, sum(a for _, _, a in rows)


